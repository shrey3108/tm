import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Text, Numeric
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func
from uuid6 import uuid7

from github_code_evaluator.app.v1.db.base_class import Base

if TYPE_CHECKING:
    from github_code_evaluator.app.v1.db.models.evaluation import Evaluation


class EvaluationReport(Base):
    """EvaluationReport ORM model.

    Tracks granular analysis reports generated by the LLM evaluation pipeline,
    including strengths, weaknesses, risks, code quality, architecture reviews,
    seniority estimates, and interview questions.
    """

    __tablename__ = "evaluation_reports"

    # PRIMARY KEY
    evaluation_report_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid7,
    )

    # FOREIGN KEYS
    evaluation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("evaluations.evaluation_id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )

    # FIELDS
    strengths: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    weaknesses: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    security_risks: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    architecture_review: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    code_quality_review: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    jd_alignment_report: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    project_alignment_report: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    jd_alignment: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    project_alignment: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    seniority_estimate: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,  # Intern | Freshers | Intermediate | Senior
    )

    interview_questions: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    extraordinary_points: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
    )

    architecture_score: Mapped[float | None] = mapped_column(
        Numeric(3, 1),
        nullable=True,
    )

    code_quality_score: Mapped[float | None] = mapped_column(
        Numeric(3, 1),
        nullable=True,
    )

    security_score: Mapped[float | None] = mapped_column(
        Numeric(3, 1),
        nullable=True,
    )

    extraordinary_score: Mapped[float | None] = mapped_column(
        Numeric(3, 1),
        nullable=True,
    )

    # TIMESTAMPS
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
    )

    # RELATIONSHIPS
    evaluation: Mapped["Evaluation"] = relationship(
        "Evaluation",
        back_populates="reports",
    )
